# Вхідні дані: однобайтові десяткові числа (в межах 128-255)
numbers = [231, 255, 178]

for n in numbers:
    # Перетворюємо число у 8-бітний двійковий формат зі збереженням старших нулів
    b = bin(n)[2:].zfill(8)
    
    # Перевіряємо, чи дорівнює рядок своєму розгорнутому варіанту
    if b == b[::-1]:
        print("True")
    else:
        print("False")