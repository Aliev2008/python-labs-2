num = input()

# Отримуємо цифри за їхніми індексами (в Python відлік починається з 0)
d1 = int(num[0])
d2 = int(num[1])
d3 = int(num[2])
d4 = int(num[3])
d5 = int(num[4])

# Перше число: сума 1-ї, 3-ї та 5-ї цифр
sum1 = d1 + d3 + d5

# Друге число: сума 2-ї та 4-ї цифр
sum2 = d2 + d4

# Склеюємо дві суми та виводимо в один рядок
print(f"{sum1}{sum2}")